import { launch } from './mock.mjs';
const BASE = process.env.APP_URL ?? 'http://localhost:4173/';
const OUT = process.argv[2] ?? '.';
const { browser, context, page, errors } = await launch();
await page.goto(BASE);
await page.waitForSelector('main li');
await page.evaluate(async () => { await navigator.serviceWorker.ready; });
await page.waitForTimeout(1500);
const manifest = await page.evaluate(async () => (await fetch(document.querySelector('link[rel=manifest]').href)).json());
console.log('manifest', manifest.name, manifest.display, manifest.icons.map((i) => i.sizes).join(','));
await context.setOffline(true);
await page.reload();
await page.waitForSelector('main li', { timeout: 10000 });
console.log('offline cards:', await page.locator('main li').count());
await page.screenshot({ path: `${OUT}/p4-offline.png` });
await page.locator('main li button').first().click();
await page.waitForSelector('text=/depth \\d+ · live/', { timeout: 20000 });
console.log('offline engine ok:', await page.locator('text=/depth \\d+ · live/').first().innerText());
console.log('errors', errors.filter((e) => !e.includes('ERR_INTERNET_DISCONNECTED')));
await browser.close();
